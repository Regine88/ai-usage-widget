$script:UsageReportMonthPattern = '^[0-9]{4}-[0-9]{2}$'

# 月份容错：非法输入回落到“当前月”，保证导出永远有确定的行为。
function ConvertTo-UsageReportMonth {
    param([string]$Value, [datetime]$Now = (Get-Date))
    if ($Value -and $Value -match $script:UsageReportMonthPattern) { return $Value }
    return $Now.ToString('yyyy-MM')
}

function Get-UsageReportMonthStart {
    param([string]$Month, [datetime]$Now = (Get-Date))
    $resolved = ConvertTo-UsageReportMonth -Value $Month -Now $Now
    $parts = $resolved.Split('-')
    return (New-Object datetime ([int]$parts[0]), ([int]$parts[1]), 1)
}

function Test-UsageReportInMonth {
    param([datetime]$Day, [string]$Month, [datetime]$Now = (Get-Date))
    $start = Get-UsageReportMonthStart -Month $Month -Now $Now
    return ($Day -ge $start -and $Day -lt $start.AddMonths(1))
}

function Get-UsageReportNumber {
    param($Value)
    if (-not (Test-FiniteNumber $Value)) { return '' }
    return ([double]$Value).ToString('0.##', [Globalization.CultureInfo]::InvariantCulture)
}

# 语言包缺键时 T 会原样返回键名，这时保留内置英文文案，
# 避免报表里出现 report.colSamples 这类键名。
function Use-UsageReportLabel {
    param($Value, [string]$Key, [string]$Fallback)
    $text = [string]$Value
    if (-not $text -or $text -eq $Key) { return $Fallback }
    return $text
}

