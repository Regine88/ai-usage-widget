        $labels.Samples = (Use-UsageReportLabel (T 'report.colSamples') 'report.colSamples' $labels.Samples)
        $labels.Days = (Use-UsageReportLabel (T 'report.colDays') 'report.colDays' $labels.Days)
        $labels.First = (Use-UsageReportLabel (T 'report.colFirst') 'report.colFirst' $labels.First)
        $labels.Last = (Use-UsageReportLabel (T 'report.colLast') 'report.colLast' $labels.Last)
        $labels.Min = (Use-UsageReportLabel (T 'report.colMin') 'report.colMin' $labels.Min)
        $labels.Max = (Use-UsageReportLabel (T 'report.colMax') 'report.colMax' $labels.Max)
        $labels.Delta = (Use-UsageReportLabel (T 'report.colDelta') 'report.colDelta' $labels.Delta)
        $labels.Slope = (Use-UsageReportLabel (T 'report.colSlope') 'report.colSlope' $labels.Slope)
