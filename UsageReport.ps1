# 按天汇总：同一天同一供应商只留一行，First/Last 取当天首末采样，
# Min/Max 取当天极值，Samples 是当天采样次数。
function Get-UsageHistoryDailyRollup {
    param($Records, [string]$Month, [string]$Id, [datetime]$Now = (Get-Date))
    $resolved = ConvertTo-UsageReportMonth -Value $Month -Now $Now
    $buckets = @{}
    $keys = New-Object System.Collections.Generic.List[string]
    foreach ($record in @(ConvertTo-UsageHistoryArray $Records)) {
        if (-not $record) { continue }
        $ts = $record.Ts
        if (-not ($ts -is [datetime])) { continue }
        if (-not (Test-UsageReportInMonth -Day $ts -Month $resolved -Now $Now)) { continue }
        $recordId = [string]$record.Id
        if (-not $recordId) { continue }
        if ($Id -and $recordId -ne $Id) { continue }
        $key = $recordId + '|' + $ts.ToString('yyyy-MM-dd')
        if (-not $buckets.ContainsKey($key)) {
            $buckets[$key] = @{
                Id = $recordId; Day = $ts.Date; DayKey = $ts.ToString('yyyy-MM-dd')
                Samples = 0; First = $null; Last = $null; Min = $null; Max = $null; Sum = 0.0
            }
            [void]$keys.Add($key)
        }
        $bucket = $buckets[$key]
        $pct = [double]$record.Pct
        $bucket.Samples = [int]$bucket.Samples + 1
        if ($null -eq $bucket.First) { $bucket.First = $pct }
        $bucket.Last = $pct
        if ($null -eq $bucket.Min -or $pct -lt [double]$bucket.Min) { $bucket.Min = $pct }
        if ($null -eq $bucket.Max -or $pct -gt [double]$bucket.Max) { $bucket.Max = $pct }
        $bucket.Sum = [double]$bucket.Sum + $pct
    }

    $rollup = @()
    foreach ($key in @($keys | Sort-Object)) {
        $bucket = $buckets[$key]
        $delta = 0.0
        if ($null -ne $bucket.First -and $null -ne $bucket.Last) { $delta = [double]$bucket.Last - [double]$bucket.First }
        $rollup += @{
            Id      = $bucket.Id
            Day     = $bucket.Day
            DayKey  = $bucket.DayKey
            Samples = [int]$bucket.Samples
            First   = $bucket.First
            Last    = $bucket.Last
            Min     = $bucket.Min
            Max     = $bucket.Max
            Delta   = $delta
            Average = ([double]$bucket.Sum / [double]$bucket.Samples)
        }
    }
    # 显式用表达式排序：Windows PowerShell 5.1 不支持按哈希表键名排序。
    return @($rollup | Sort-Object -Property @{ Expression = { $_.DayKey } }, @{ Expression = { $_.Id } })
}

# 月度汇总：每个供应商一行，斜率复用 UsageHistory.ps1 的最小二乘实现。
function Get-UsageHistoryMonthlySummary {
    param($Records, [string]$Month, [datetime]$Now = (Get-Date))
    $resolved = ConvertTo-UsageReportMonth -Value $Month -Now $Now
    $rollup = @(Get-UsageHistoryDailyRollup -Records $Records -Month $resolved -Now $Now)
    $aggregates = @{}
    $ids = New-Object System.Collections.Generic.List[string]
    foreach ($entry in $rollup) {
        $id = [string]$entry.Id
        if (-not $aggregates.ContainsKey($id)) {
            $aggregates[$id] = @{
                Id = $id; Samples = 0; Days = 0; First = $null; Last = $null
                Min = $null; Max = $null; Sum = 0.0; PeakDay = $null; PeakPct = $null; Series = @()
            }
            [void]$ids.Add($id)
        }
        $agg = $aggregates[$id]
        $agg.Samples = [int]$agg.Samples + [int]$entry.Samples
        $agg.Days = [int]$agg.Days + 1
        if ($null -eq $agg.First) { $agg.First = [double]$entry.First }
        $agg.Last = [double]$entry.Last
        if ($null -eq $agg.Min -or [double]$entry.Min -lt [double]$agg.Min) { $agg.Min = [double]$entry.Min }
        if ($null -eq $agg.Max -or [double]$entry.Max -gt [double]$agg.Max) { $agg.Max = [double]$entry.Max }
        $agg.Sum = [double]$agg.Sum + ([double]$entry.Average * [int]$entry.Samples)
        if ($null -eq $agg.PeakPct -or [double]$entry.Last -gt [double]$agg.PeakPct) {
            $agg.PeakPct = [double]$entry.Last
            $agg.PeakDay = $entry.DayKey
        }
        $agg.Series = @($agg.Series) + @(@{ Day = $entry.Day; Pct = [double]$entry.Last })
    }

    $summary = @()
    foreach ($id in @($ids | Sort-Object)) {
        $agg = $aggregates[$id]
        $delta = 0.0
        if ($null -ne $agg.First -and $null -ne $agg.Last) { $delta = [double]$agg.Last - [double]$agg.First }
        $average = 0.0
        if ([int]$agg.Samples -gt 0) { $average = [double]$agg.Sum / [double]$agg.Samples }
        $slope = $null
        try { $slope = Get-UsageTrendSlope $agg.Series } catch { $slope = $null }
        $summary += @{
            Id = $agg.Id; Samples = [int]$agg.Samples; Days = [int]$agg.Days
            First = $agg.First; Last = $agg.Last; Min = $agg.Min; Max = $agg.Max
            Delta = $delta; Average = $average; SlopePerDay = $slope
            PeakDay = $agg.PeakDay; PeakPct = $agg.PeakPct
        }
    }
    return @($summary)
}

# 历史里出现过的月份，新的在前；用于菜单与“最近 N 个月”导出。
function Get-UsageHistoryMonths {
    param($Records, [int]$Limit = 0)
    $months = New-Object System.Collections.Generic.List[string]
    foreach ($record in @(ConvertTo-UsageHistoryArray $Records)) {
        if (-not $record) { continue }
        $ts = $record.Ts
        if (-not ($ts -is [datetime])) { continue }
        $key = $ts.ToString('yyyy-MM')
        if (-not $months.Contains($key)) { [void]$months.Add($key) }
    }
    $sorted = @($months | Sort-Object -Descending)
    if ($Limit -gt 0 -and $sorted.Count -gt $Limit) { $sorted = @($sorted[0..($Limit - 1)]) }
    return @($sorted)
}

function ConvertTo-UsageReportCsv {
    param($Rollup)
    $builder = New-Object System.Text.StringBuilder
    [void]$builder.Append("day,provider,samples,first,last,min,max,delta`r`n")
    foreach ($entry in @($Rollup)) {
        if (-not $entry) { continue }
        $fields = @(
            (ConvertTo-UsageHistoryField ([string]$entry.DayKey))
            (ConvertTo-UsageHistoryField ([string]$entry.Id))
            ([string][int]$entry.Samples)
            (Get-UsageReportNumber $entry.First)
            (Get-UsageReportNumber $entry.Last)
            (Get-UsageReportNumber $entry.Min)
            (Get-UsageReportNumber $entry.Max)
            (Get-UsageReportNumber $entry.Delta)
        )
        [void]$builder.Append(($fields -join ','))
        [void]$builder.Append("`r`n")
    }
    return $builder.ToString()
}

function ConvertTo-UsageReportMarkdownText {
    param($Value)
    $text = [string]$Value
    return $text.Replace('|', '\|').Replace("`r", ' ').Replace("`n", ' ')
}

function ConvertTo-UsageReportMarkdown {
    param($Summary, $Rollup, [string]$Month, [datetime]$GeneratedAt = (Get-Date))
    $labels = Get-UsageReportLabels
    $resolved = ConvertTo-UsageReportMonth -Value $Month
    $lines = New-Object System.Collections.Generic.List[string]
    [void]$lines.Add(('# ' + $labels.Title + ' · ' + $resolved))
    [void]$lines.Add('')
    [void]$lines.Add(($labels.GeneratedAt -f $GeneratedAt.ToString('yyyy-MM-dd HH:mm:ss')))
    [void]$lines.Add('')
    [void]$lines.Add(('## ' + $labels.Heading))
    [void]$lines.Add('')
    $items = @($Summary)
    if ($items.Count -eq 0) {
        [void]$lines.Add($labels.NoData)
    } else {
        [void]$lines.Add(('| {0} | {1} | {2} | {3} | {4} | {5} | {6} | {7} | {8} |' -f
            $labels.Provider, $labels.Samples, $labels.Days, $labels.First, $labels.Last,
            $labels.Min, $labels.Max, $labels.Delta, $labels.Slope))
        [void]$lines.Add('| --- | --- | --- | --- | --- | --- | --- | --- | --- |')
        foreach ($item in $items) {
            $slope = '-'
            if (Test-FiniteNumber $item.SlopePerDay) { $slope = ($labels.PerDay -f (Get-UsageReportNumber $item.SlopePerDay)) }
            [void]$lines.Add(('| {0} | {1} | {2} | {3} | {4} | {5} | {6} | {7} | {8} |' -f
                (ConvertTo-UsageReportMarkdownText $item.Id), [int]$item.Samples, [int]$item.Days,
                (Get-UsageReportNumber $item.First), (Get-UsageReportNumber $item.Last),
                (Get-UsageReportNumber $item.Min), (Get-UsageReportNumber $item.Max),
                (Get-UsageReportNumber $item.Delta), $slope))
        }
    }
    [void]$lines.Add('')
    [void]$lines.Add(('## ' + $labels.DailyHeading))
    [void]$lines.Add('')
    $days = @($Rollup)
    if ($days.Count -eq 0) {
        [void]$lines.Add($labels.NoData)
    } else {
        [void]$lines.Add(('| {0} | {1} | {2} | {3} | {4} | {5} | {6} |' -f
            'Day', $labels.Provider, $labels.Samples, $labels.First, $labels.Last, $labels.Min, $labels.Max))
        [void]$lines.Add('| --- | --- | --- | --- | --- | --- | --- |')
        foreach ($entry in $days) {
            [void]$lines.Add(('| {0} | {1} | {2} | {3} | {4} | {5} | {6} |' -f
                $entry.DayKey, (ConvertTo-UsageReportMarkdownText $entry.Id), [int]$entry.Samples,
                (Get-UsageReportNumber $entry.First), (Get-UsageReportNumber $entry.Last),
                (Get-UsageReportNumber $entry.Min), (Get-UsageReportNumber $entry.Max)))
        }
    }
    [void]$lines.Add('')
    [void]$lines.Add(('> ' + $labels.Footer))
    return (($lines -join "`n") + "`n")
}

