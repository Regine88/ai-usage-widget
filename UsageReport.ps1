# 自包含 HTML：样式内联，不引用任何外部资源，方便直接双击打开或当作附件发送。
function ConvertTo-UsageReportHtml {
    param($Summary, $Rollup, [string]$Month, [datetime]$GeneratedAt = (Get-Date))
    $labels = Get-UsageReportLabels
    $resolved = ConvertTo-UsageReportMonth -Value $Month
    $stamp = (ConvertTo-UsageReportHtmlText ($labels.GeneratedAt -f $GeneratedAt.ToString('yyyy-MM-dd HH:mm:ss')))
    $builder = New-Object System.Text.StringBuilder
    [void]$builder.Append("<!DOCTYPE html>`n<html lang=""en"">`n<head>`n<meta charset=""utf-8"">`n")
    [void]$builder.Append(('<title>{0} · {1}</title>' -f (ConvertTo-UsageReportHtmlText $labels.Title), $resolved) + "`n")
    [void]$builder.Append((Get-UsageReportHtmlStyle) + "`n")
    [void]$builder.Append("</head>`n<body>`n")
    [void]$builder.Append(('<h1>{0} · {1}</h1>' -f (ConvertTo-UsageReportHtmlText $labels.Title), $resolved) + "`n")
    [void]$builder.Append(('<p class="meta">{0}</p>' -f $stamp) + "`n")
    [void]$builder.Append(('<h2>{0}</h2>' -f (ConvertTo-UsageReportHtmlText $labels.Heading)) + "`n")
    $items = @($Summary)
    if ($items.Count -eq 0) {
        [void]$builder.Append(('<p class="meta">{0}</p>' -f (ConvertTo-UsageReportHtmlText $labels.NoData)) + "`n")
    } else {
        [void]$builder.Append("<table>`n<thead><tr>")
        foreach ($head in @($labels.Provider, $labels.Samples, $labels.Days, $labels.First, $labels.Last, $labels.Min, $labels.Max, $labels.Delta, $labels.Slope)) {
            [void]$builder.Append(('<th>{0}</th>' -f (ConvertTo-UsageReportHtmlText $head)))
        }
        [void]$builder.Append("</tr></thead>`n<tbody>`n")
        foreach ($item in $items) {
            $slope = '-'
            if (Test-FiniteNumber $item.SlopePerDay) { $slope = ($labels.PerDay -f (Get-UsageReportNumber $item.SlopePerDay)) }
            [void]$builder.Append('<tr>')
            foreach ($cell in @(
                    (ConvertTo-UsageReportHtmlText $item.Id), [string][int]$item.Samples, [string][int]$item.Days,
                    (Get-UsageReportNumber $item.First), (Get-UsageReportNumber $item.Last),
                    (Get-UsageReportNumber $item.Min), (Get-UsageReportNumber $item.Max),
                    (Get-UsageReportNumber $item.Delta), (ConvertTo-UsageReportHtmlText $slope))) {
                [void]$builder.Append(('<td>{0}</td>' -f $cell))
            }
            [void]$builder.Append("</tr>`n")
        }
        [void]$builder.Append("</tbody>`n</table>`n")
    }
    [void]$builder.Append(('<h2>{0}</h2>' -f (ConvertTo-UsageReportHtmlText $labels.DailyHeading)) + "`n")
    $days = @($Rollup)
    if ($days.Count -eq 0) {
        [void]$builder.Append(('<p class="meta">{0}</p>' -f (ConvertTo-UsageReportHtmlText $labels.NoData)) + "`n")
    } else {
        [void]$builder.Append("<table>`n<thead><tr>")
        foreach ($head in @('Day', $labels.Provider, $labels.Samples, $labels.First, $labels.Last, $labels.Min, $labels.Max)) {
            [void]$builder.Append(('<th>{0}</th>' -f (ConvertTo-UsageReportHtmlText $head)))
        }
        [void]$builder.Append("</tr></thead>`n<tbody>`n")
        foreach ($entry in $days) {
            [void]$builder.Append('<tr>')
            foreach ($cell in @(
                    (ConvertTo-UsageReportHtmlText $entry.DayKey), (ConvertTo-UsageReportHtmlText $entry.Id), [string][int]$entry.Samples,
                    (Get-UsageReportNumber $entry.First), (Get-UsageReportNumber $entry.Last),
                    (Get-UsageReportNumber $entry.Min), (Get-UsageReportNumber $entry.Max))) {
                [void]$builder.Append(('<td>{0}</td>' -f $cell))
            }
            [void]$builder.Append("</tr>`n")
        }
        [void]$builder.Append("</tbody>`n</table>`n")
    }
    [void]$builder.Append(('<footer>{0}</footer>' -f (ConvertTo-UsageReportHtmlText $labels.Footer)) + "`n")
    [void]$builder.Append("</body>`n</html>`n")
    return $builder.ToString()
}

function Get-UsageReportFileName {
    param([string]$Month, [string]$Extension)
    $resolved = ConvertTo-UsageReportMonth -Value $Month
    $ext = [string]$Extension
    if (-not $ext) { $ext = 'csv' }
    return ('ai-usage-report-{0}.{1}' -f $resolved, $ext.TrimStart('.'))
}

# ---------- 多月对比 ----------

# 对比用的月份集合：默认取历史里最近的几个有数据的月份，返回升序（早的在前），
# 这样报表读起来就是从旧到新的时间线。
function Get-UsageReportComparisonMonths {
    param($Records, [int]$Months = 3, [datetime]$Now = (Get-Date))
    $limit = [int]$Months
    if ($limit -lt 1) { $limit = 1 }
    $recent = @(Get-UsageHistoryMonths -Records $Records -Limit $limit)
    if ($recent.Count -eq 0) { return @() }
    return @($recent | Sort-Object)
}

# 对比区间文字：'2026-07 → 2026-09'；只有一个月时就是该月本身，没有月份时用当前月。
function Get-UsageReportComparisonRange {
    param($Months, [datetime]$Now = (Get-Date))
    $keys = @(ConvertTo-UsageHistoryArray $Months | ForEach-Object { [string]$_ } | Where-Object { $_ })
    if ($keys.Count -eq 0) { return (ConvertTo-UsageReportMonth -Value $null -Now $Now) }
    $first = ConvertTo-UsageReportMonth -Value $keys[0] -Now $Now
    $last = ConvertTo-UsageReportMonth -Value $keys[$keys.Count - 1] -Now $Now
    if ($first -eq $last) { return $first }
    return ('{0} → {1}' -f $first, $last)
}

# 环比变化文字：正数带 + 号，没有可比数据时用 '-'。
function Get-UsageReportChangeText {
    param($Change)
    if (-not (Test-FiniteNumber $Change)) { return '-' }
    $value = [double]$Change
    $text = (Get-UsageReportNumber $value)
    if ($value -gt 0) { return ('+' + $text) }
    return $text
}

# 对比表的数值单元格：该月没有采样时统一显示占位符 '-'，
# 而不是留空，让「供应商 × 月份」的每个格子都有确定含义。
function Get-UsageReportComparisonCell {
    param($Value)
    if (-not (Test-FiniteNumber $Value)) { return '-' }
    return (Get-UsageReportNumber $Value)
}

# 多月对比行：一行 = 一个供应商的一个月。环比取“上一个日历月”的月末，
# 即使那个月不在选中区间里也照样能算出来；上月没有该供应商的采样时为 $null。
# 行集是「区间内出现过的供应商 × 选中月份」的完整组合：某个月没有采样的供应商
# 也会占一行，各数值列为 $null，渲染成占位符 '-'。
function Get-UsageHistoryMonthComparison {
    param($Records, $Months, [datetime]$Now = (Get-Date))
    $keys = @(ConvertTo-UsageHistoryArray $Months | ForEach-Object { [string]$_ } | Where-Object { $_ })
    $byMonth = @{}
    $idTable = @{}
    foreach ($key in $keys) {
        $month = ConvertTo-UsageReportMonth -Value $key -Now $Now
        $bucket = @{}
        foreach ($item in @(Get-UsageHistoryMonthlySummary -Records $Records -Month $month -Now $Now)) {
            $id = [string]$item.Id
            if (-not $id) { continue }
            $bucket[$id] = $item
            $idTable[$id] = $true
        }
        $byMonth[$month] = $bucket
    }
    $knownIds = @($idTable.Keys | Sort-Object)
    $rows = @()
    foreach ($key in $keys) {
        $month = ConvertTo-UsageReportMonth -Value $key -Now $Now
        $previousMonth = (Get-UsageReportMonthStart -Month $month -Now $Now).AddMonths(-1).ToString('yyyy-MM')
        $previous = @{}
        foreach ($item in @(Get-UsageHistoryMonthlySummary -Records $Records -Month $previousMonth -Now $Now)) {
            $previous[[string]$item.Id] = $item
        }
        $bucket = $byMonth[$month]
        foreach ($id in $knownIds) {
            $item = $null
            if ($bucket.ContainsKey($id)) { $item = $bucket[$id] }
            $last = $null
            if ($item) { $last = $item.Last }
            $change = $null
            $previousLast = $null
            if ($previous.ContainsKey($id)) {
                $candidate = $previous[$id].Last
                if ((Test-FiniteNumber $candidate) -and (Test-FiniteNumber $last)) {
                    $previousLast = [double]$candidate
                    $change = [double]$last - $previousLast
                }
            }
            if (-not $item) {
                $rows += @{
                    Id = $id; Month = $month
                    Samples = $null; Days = $null
                    First = $null; Last = $null; Min = $null; Max = $null
                    Delta = $null; Average = $null; SlopePerDay = $null
                    PreviousMonth = $previousMonth; PreviousLast = $previousLast; Change = $change
                }
            } else {
                $rows += @{
                    Id = $id; Month = $month
                    Samples = [int]$item.Samples; Days = [int]$item.Days
                    First = $item.First; Last = $item.Last; Min = $item.Min; Max = $item.Max
                    Delta = $item.Delta; Average = $item.Average; SlopePerDay = $item.SlopePerDay
                    PreviousMonth = $previousMonth; PreviousLast = $previousLast; Change = $change
                }
            }
        }
    }
    # 显式用表达式排序：Windows PowerShell 5.1 不支持按哈希表键名排序。
    return @($rows | Sort-Object -Property @{ Expression = { $_.Id } }, @{ Expression = { $_.Month } })
}

# 多月对比文案：先取通用报表文案，再覆盖对比专用的几条。
function Get-UsageReportComparisonLabels {
    $labels = Get-UsageReportLabels
    $labels.Title = 'AI usage report - month over month'
    $labels.Heading = 'Month over month'
    $labels.Month = 'Month'
    $labels.Change = 'Change'
    $labels.Note = '"-" means no samples that month, or nothing to compare with the previous month'
    if (Get-Command T -ErrorAction SilentlyContinue) {
        $labels.Title = (Use-WidgetTextFallback (T 'report.compareTitle') 'report.compareTitle' $labels.Title)
        $labels.Heading = (Use-WidgetTextFallback (T 'report.compareHeading') 'report.compareHeading' $labels.Heading)
        $labels.Month = (Use-WidgetTextFallback (T 'report.colMonth') 'report.colMonth' $labels.Month)
        $labels.Change = (Use-WidgetTextFallback (T 'report.colChange') 'report.colChange' $labels.Change)
        $labels.Note = (Use-WidgetTextFallback (T 'report.compareNote') 'report.compareNote' $labels.Note)
    }
    return $labels
}

function ConvertTo-UsageReportComparisonMarkdown {
    param($Comparison, $Months, [datetime]$GeneratedAt = (Get-Date))
    $labels = Get-UsageReportComparisonLabels
    $range = Get-UsageReportComparisonRange -Months $Months
    $lines = New-Object System.Collections.Generic.List[string]
    [void]$lines.Add(('# ' + $labels.Title + ' · ' + $range))
    [void]$lines.Add('')
    [void]$lines.Add(($labels.GeneratedAt -f $GeneratedAt.ToString('yyyy-MM-dd HH:mm:ss')))
    [void]$lines.Add('')
    [void]$lines.Add(('## ' + $labels.Heading))
    [void]$lines.Add('')
    $items = @($Comparison)
    if ($items.Count -eq 0) {
        [void]$lines.Add($labels.NoData)
    } else {
        [void]$lines.Add(('| {0} | {1} | {2} | {3} | {4} | {5} | {6} | {7} | {8} |' -f
            $labels.Provider, $labels.Month, $labels.Samples, $labels.Days,
            $labels.First, $labels.Last, $labels.Min, $labels.Max, $labels.Change))
        [void]$lines.Add('| --- | --- | --- | --- | --- | --- | --- | --- | --- |')
        foreach ($item in $items) {
            [void]$lines.Add(('| {0} | {1} | {2} | {3} | {4} | {5} | {6} | {7} | {8} |' -f
                (ConvertTo-UsageReportMarkdownText $item.Id), (ConvertTo-UsageReportMarkdownText $item.Month),
                (Get-UsageReportComparisonCell $item.Samples), (Get-UsageReportComparisonCell $item.Days),
                (Get-UsageReportComparisonCell $item.First), (Get-UsageReportComparisonCell $item.Last),
                (Get-UsageReportComparisonCell $item.Min), (Get-UsageReportComparisonCell $item.Max),
                (ConvertTo-UsageReportMarkdownText (Get-UsageReportChangeText $item.Change))))
        }
        [void]$lines.Add('')
        [void]$lines.Add($labels.Note)
    }
    [void]$lines.Add('')
    [void]$lines.Add(('> ' + $labels.Footer))
    return (($lines -join "`n") + "`n")
}

function ConvertTo-UsageReportComparisonHtml {
    param($Comparison, $Months, [datetime]$GeneratedAt = (Get-Date))
    $labels = Get-UsageReportComparisonLabels
    $range = Get-UsageReportComparisonRange -Months $Months
    $stamp = (ConvertTo-UsageReportHtmlText ($labels.GeneratedAt -f $GeneratedAt.ToString('yyyy-MM-dd HH:mm:ss')))
    $builder = New-Object System.Text.StringBuilder
    [void]$builder.Append("<!DOCTYPE html>`n<html lang=""en"">`n<head>`n<meta charset=""utf-8"">`n")
    [void]$builder.Append(('<title>{0} · {1}</title>' -f (ConvertTo-UsageReportHtmlText $labels.Title), $range) + "`n")
    [void]$builder.Append((Get-UsageReportHtmlStyle) + "`n")
    [void]$builder.Append("</head>`n<body>`n")
    [void]$builder.Append(('<h1>{0} · {1}</h1>' -f (ConvertTo-UsageReportHtmlText $labels.Title), $range) + "`n")
    [void]$builder.Append(('<p class="meta">{0}</p>' -f $stamp) + "`n")
    [void]$builder.Append(('<h2>{0}</h2>' -f (ConvertTo-UsageReportHtmlText $labels.Heading)) + "`n")
    $items = @($Comparison)
    if ($items.Count -eq 0) {
        [void]$builder.Append(('<p class="meta">{0}</p>' -f (ConvertTo-UsageReportHtmlText $labels.NoData)) + "`n")
    } else {
        [void]$builder.Append("<table>`n<thead><tr>")
        foreach ($head in @($labels.Provider, $labels.Month, $labels.Samples, $labels.Days, $labels.First, $labels.Last, $labels.Min, $labels.Max, $labels.Change)) {
            [void]$builder.Append(('<th>{0}</th>' -f (ConvertTo-UsageReportHtmlText $head)))
        }
        [void]$builder.Append("</tr></thead>`n<tbody>`n")
        foreach ($item in $items) {
            [void]$builder.Append('<tr>')
            foreach ($cell in @(
                    (ConvertTo-UsageReportHtmlText $item.Id), (ConvertTo-UsageReportHtmlText $item.Month),
                    (Get-UsageReportComparisonCell $item.Samples), (Get-UsageReportComparisonCell $item.Days),
                    (Get-UsageReportComparisonCell $item.First), (Get-UsageReportComparisonCell $item.Last),
                    (Get-UsageReportComparisonCell $item.Min), (Get-UsageReportComparisonCell $item.Max),
                    (ConvertTo-UsageReportHtmlText (Get-UsageReportChangeText $item.Change)))) {
                [void]$builder.Append(('<td>{0}</td>' -f $cell))
            }
            [void]$builder.Append("</tr>`n")
        }
        [void]$builder.Append("</tbody>`n</table>`n")
        [void]$builder.Append(('<p class="meta">{0}</p>' -f (ConvertTo-UsageReportHtmlText $labels.Note)) + "`n")
    }
    [void]$builder.Append(('<footer>{0}</footer>' -f (ConvertTo-UsageReportHtmlText $labels.Footer)) + "`n")
    [void]$builder.Append("</body>`n</html>`n")
    return $builder.ToString()
}

function Get-UsageReportComparisonFileName {
    param($Months, [string]$Extension)
    $keys = @(ConvertTo-UsageHistoryArray $Months | ForEach-Object { [string]$_ } | Where-Object { $_ })
    $ext = [string]$Extension
    if (-not $ext) { $ext = 'md' }
    $ext = $ext.TrimStart('.')
    $first = ConvertTo-UsageReportMonth -Value $(if ($keys.Count -gt 0) { $keys[0] } else { $null })
    $last = ConvertTo-UsageReportMonth -Value $(if ($keys.Count -gt 0) { $keys[$keys.Count - 1] } else { $null })
    if ($first -eq $last) { return ('ai-usage-comparison-{0}.{1}' -f $first, $ext) }
    return ('ai-usage-comparison-{0}_{1}.{2}' -f $first, $last, $ext)
}
